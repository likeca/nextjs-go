-- Reverse of 000002_rbac_bootstrap.up.sql — removes the seeded RBAC rows.
-- Order matters: role_permission references roles.
DELETE FROM role_permission
WHERE role_id IN ('00000000-0000-0000-0000-000000000101', '00000000-0000-0000-0000-000000000102');

DELETE FROM "role"
WHERE id IN ('00000000-0000-0000-0000-000000000101', '00000000-0000-0000-0000-000000000102');

DELETE FROM permission
WHERE id BETWEEN '00000000-0000-0000-0000-000000000001' AND '00000000-0000-0000-0000-000000000032';
